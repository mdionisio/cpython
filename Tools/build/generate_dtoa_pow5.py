#!/usr/bin/env python3
"""Generate Python/dtoa_pow5.h.

The header contains 128-bit approximations of the powers of five 5**q for
q in [DTOA_POW5_MIN, DTOA_POW5_MAX], as used by the Eisel-Lemire fast path
in Python/dtoa.c.  Each power is normalized so that its most significant bit
is bit 127 and is stored as two 64-bit words (high word first).

For q >= 0 the value is truncated; for q < 0 it is the reciprocal 2**b // 5**-q
rounded up.  See: Daniel Lemire, "Number Parsing at a Gigabyte per Second",
Software: Practice and Experience 51 (8), 2021.
"""

import argparse
import sys

POW5_MIN = -342
POW5_MAX = 308


def pow5_128(q):
    if q >= 0:
        power5 = 5 ** q
        while power5 < (1 << 127):
            power5 *= 2
        while power5 >= (1 << 128):
            power5 //= 2
        return power5
    power5 = 5 ** -q
    z = power5.bit_length()
    if (1 << (z - 1)) == power5:
        z -= 1
    if q >= -27:
        c = 2 ** (z + 127) // power5 + 1
    else:
        c = 2 ** (2 * z + 2 * 64) // power5 + 1
        while c >= (1 << 128):
            c //= 2
    return c


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('output', nargs='?', default=None)
    args = parser.parse_args()

    lines = [
        '/* Generated by Tools/build/generate_dtoa_pow5.py.  DO NOT EDIT. */',
        '',
        '#ifndef Py_DTOA_POW5_H',
        '#define Py_DTOA_POW5_H',
        '',
        f'#define DTOA_POW5_MIN ({POW5_MIN})',
        f'#define DTOA_POW5_MAX {POW5_MAX}',
        '',
        '/* 128-bit normalized approximations of 5**q, for q in',
        '   [DTOA_POW5_MIN, DTOA_POW5_MAX]: high word, then low word. */',
        'static const uint64_t dtoa_pow5_128[2 * (DTOA_POW5_MAX - DTOA_POW5_MIN + 1)] = {',
    ]
    mask = (1 << 64) - 1
    for q in range(POW5_MIN, POW5_MAX + 1):
        c = pow5_128(q)
        assert (1 << 127) <= c < (1 << 128), q
        lines.append(f'    0x{c >> 64:016x}, 0x{c & mask:016x}, /* 5**{q} */')
    lines += ['};', '', '#endif /* !Py_DTOA_POW5_H */', '']
    text = '\n'.join(lines)

    if args.output is None:
        sys.stdout.write(text)
    else:
        with open(args.output, 'w', encoding='ascii', newline='\n') as f:
            f.write(text)


if __name__ == '__main__':
    main()
